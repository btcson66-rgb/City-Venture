#!/bin/bash
# Encode a Movie Maker capture of the ad bot (game/tests/walkthrough/ad_reel.gd) into a 16:9 MP4 and a 9:16
# vertical MP4 (blurred fill) with a music bed.
#   1. record:  godot --path game --rendering-driver opengl3 --resolution 1280x720 \
#                 --write-movie /tmp/ad/f.png --fixed-fps 30 --quit-after 2400 -- --bot=ad --ad=tycoon --lang=zh_TW
#               (the bot log prints AD_START frame=N / AD_END frame=M)
#   2. encode:  tools/media/make_ads.sh /tmp/ad N M tycoon docs/media/ads/ad_tycoon_zh
#               -> ad_tycoon_zh.mp4 (1280x720) and ad_tycoon_zh_vertical.mp4 (1080x1920)
# Music is generated by tools/media/make_ad_music.py (placeholder until licensed tracks are chosen).
set -euo pipefail
FRAMES="$1"; START="$2"; END="$3"; MOOD="$4"; OUT="$5"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
N=$((END - START))
SECS=$(python3 -c "print(round($N / 30.0, 3))")
TMP="$(mktemp -d)"
python3 "$ROOT/tools/media/make_ad_music.py" "$TMP/music.wav" "$MOOD" "$SECS" 6.0 >/dev/null
mkdir -p "$(dirname "$OUT")"
ffmpeg -y -loglevel error \
  -framerate 30 -start_number "$START" -i "$FRAMES/f%08d.png" -i "$TMP/music.wav" \
  -frames:v "$N" -vf "scale=1280:720:flags=neighbor,format=yuv420p" \
  -c:v libx264 -preset slow -crf 20 -tune animation -movflags +faststart \
  -af "loudnorm=I=-14:TP=-1.0:LRA=9" -c:a aac -b:a 160k -ar 44100 -shortest "$OUT.mp4"
# 9:16: the game picture full-width in the middle over a blurred, darkened fill of itself
ffmpeg -y -loglevel error -i "$OUT.mp4" \
  -filter_complex "[0:v]split[a][b];[a]scale=3414:1920:flags=bilinear,crop=1080:1920,boxblur=24:2,eq=brightness=-0.18[bg];[b]scale=1080:608:flags=neighbor[fg];[bg][fg]overlay=0:(H-h)/2,format=yuv420p" \
  -c:v libx264 -preset slow -crf 21 -movflags +faststart -c:a copy "${OUT}_vertical.mp4"
rm -rf "$TMP"
for f in "$OUT.mp4" "${OUT}_vertical.mp4"; do echo "$f  ${SECS}s  $(du -h "$f" | cut -f1)"; done
