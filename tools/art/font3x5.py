def text_width(s):
    return sum(len(GLYPHS.get(ch, GLYPHS[" "])[0]) + 1 for ch in s.upper()) - 1


def draw_text(img, x, y, s, col, scale=1):
    cx = x
    for ch in s.upper():
        g = GLYPHS.get(ch, GLYPHS[" "])
        for gy, row in enumerate(g):
            for gx, v in enumerate(row):
                if v == "1":
                    for sx in range(scale):
                        for sy in range(scale):
                            put(img, cx + gx * scale + sx, y + gy * scale + sy, col)
        cx += (len(g[0]) + 1) * scale
    return cx


def draw_text_centered(img, cx, y, s, col, scale=1):
    w = text_width(s) * scale
    return draw_text(img, cx - w // 2, y, s, col, scale)
